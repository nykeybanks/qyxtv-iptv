const displayNames = new Map<string, Intl.DisplayNames>()
export function displayName(code: string, locale: Locale, type: 'region' | 'language', fallback = code) {
  if (code === 'ALL') return translate(locale, 'Worldwide')
  try {
    const key = `${locale}:${type}`
    if (!displayNames.has(key)) displayNames.set(key, new Intl.DisplayNames([locale], { type }))
    const name = displayNames.get(key)?.of(code)
    return name === code ? fallback : name ?? fallback
  } catch { return fallback }
}
